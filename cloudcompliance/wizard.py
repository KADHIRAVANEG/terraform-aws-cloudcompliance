def run_wizard(
    provider: Optional[str] = None,
    framework: Optional[str] = None,
    env: Optional[str] = None,
    services: Optional[List[str]] = None,
    region: Optional[str] = None,
    project_name: Optional[str] = None,
    output_dir: Optional[Path] = None,
    non_interactive: bool = False,
) -> Dict[str, Path]:
    """
    Execute the interactive starter wizard to bootstrap a compliant Terraform configuration.
    """
    target_dir = Path(output_dir) if output_dir else Path.cwd()
    target_dir.mkdir(parents=True, exist_ok=True)

    console.print(Panel.fit(
        "[bold cyan]⚡ CloudCompliance — Interactive Starter Wizard[/bold cyan]\n"
        "[dim]Scaffold compliance-ready infrastructure as code tailored to your stack.[/dim]",
        border_style="cyan"
    ))

    # 1. Cloud Provider
    if not provider:
        if non_interactive or not sys.stdin.isatty():
            provider = "aws"
        else:
            provider = Prompt.ask(
                "1. Which cloud provider are you targeting?",
                choices=["aws", "azure", "gcp"],
                default="aws"
            )
    provider = provider.lower()

    # 2. Compliance Framework
    if not framework:
        if non_interactive or not sys.stdin.isatty():
            framework = "soc2"
        else:
            framework = Prompt.ask(
                "2. Which primary compliance framework do you need to satisfy?",
                choices=["soc2", "hipaa", "pcidss"],
                default="soc2"
            )
    framework = framework.lower()

    # 3. Environment tier
    if not env:
        if non_interactive or not sys.stdin.isatty():
            env = "dev"
        else:
            env = Prompt.ask(
                "3. Which environment tier are you configuring?",
                choices=["dev", "staging", "prod"],
                default="dev"
            )
    env = env.lower()

    # 4. Project name & region
    if not project_name:
        if non_interactive or not sys.stdin.isatty():
            project_name = "cloudcompliance-app"
        else:
            project_name = Prompt.ask("4. Enter project / workload name", default="cloudcompliance-app")

    default_region = "us-east-1" if provider == "aws" else "eastus" if provider == "azure" else "us-central1"
    if not region:
        if non_interactive or not sys.stdin.isatty():
            region = default_region
        else:
            region = Prompt.ask(f"5. Target {provider.upper()} deployment region", default=default_region)

    # Generate file contents based on chosen cloud provider
    if provider == "azure":
        main_tf_content = AZURE_MAIN_TF.format(
            framework_upper=framework.upper(),
            environment=env,
        )
        variables_tf_content = AZURE_VARIABLES_TF.format(
            region=region,
            environment=env,
            project_name=project_name,
        )
        tfvars_content = AZURE_TFVARS.format(
            region=region,
            environment=env,
            project_name=project_name,
        )
        env_content = AZURE_ENV_EXAMPLE
    elif provider == "gcp":
        main_tf_content = GCP_MAIN_TF.format(
            framework_upper=framework.upper(),
            framework_lower=framework.lower(),
            environment=env,
        )
        variables_tf_content = GCP_VARIABLES_TF.format(
            region=region,
            environment=env,
            project_name=project_name,
        )
        tfvars_content = GCP_TFVARS.format(
            region=region,
            environment=env,
            project_name=project_name,
        )
        env_content = GCP_ENV_EXAMPLE
    else:
        main_tf_content = AWS_MAIN_TF.format(
            framework_upper=framework.upper(),
            environment=env,
            provider_upper=provider.upper(),
        )
        variables_tf_content = AWS_VARIABLES_TF.format(
            region=region,
            environment=env,
            project_name=project_name,
        )
        tfvars_content = AWS_TFVARS.format(
            region=region,
            environment=env,
            project_name=project_name,
        )
        env_content = ENV_EXAMPLE.format(region=region)

    # Write files
    created_files: Dict[str, Path] = {}
    files_to_write = {
        "main.tf": main_tf_content,
        "variables.tf": variables_tf_content,
        "terraform.tfvars": tfvars_content,
        ".env.example": env_content,
    }

    for filename, content in files_to_write.items():
        file_path = target_dir / filename
        with open(file_path, "w") as f:
            f.write(content)
        created_files[filename] = file_path

    # Print summary
    console.print()
    console.print(f"[bold green]✔ Compliance project successfully initialized in {target_dir}![/bold green]\n")
    for fname, fpath in created_files.items():
        console.print(f"  • [cyan]{fname}[/cyan] → [dim]{fpath}[/dim]")

    console.print()
    console.print(Panel(
        f"[bold]Next Steps to Achieve Instant {framework.upper()} Compliance:[/bold]\n\n"
        f"  1. Review generated files:   [cyan]cd {target_dir}[/cyan]\n"
        f"  2. Initialize Terraform:     [cyan]terraform init[/cyan]\n"
        f"  3. Validate configuration:   [cyan]terraform plan[/cyan]\n"
        f"  4. Apply baseline controls:  [cyan]terraform apply[/cyan]\n"
        f"  5. Generate compliance proof:[cyan]cloudcompliance report --framework {framework} --pdf --sarif[/cyan]\n",
        title="[bold green]🚀 Ready for Deployment[/bold green]",
        border_style="green"
    ))

    return created_files
