#!/usr/bin/env python3
"""
CloudCompliance — Interactive Starter Wizard (`cloudcompliance init`)
Scaffolds tailored, production-ready, compliance-first Terraform configurations
(main.tf, variables.tf, terraform.tfvars, and .env.example) for AWS, Azure, or GCP.
"""

import sys
from pathlib import Path
from typing import List, Dict, Optional
from rich.console import Console
from rich.panel import Panel
from rich.prompt import Prompt, Confirm

console = Console()

AWS_MAIN_TF = '''# Generated by CloudCompliance Wizard (cloudcompliance init)
# Framework: {framework_upper} | Environment: {environment} | Provider: {provider_upper}

terraform {{
  required_version = ">= 1.5.0"
  required_providers {{
    aws = {{
      source  = "hashicorp/aws"
      version = "~> 5.0"
    }}
  }}
}}

provider "aws" {{
  region = var.aws_region

  default_tags {{
    tags = {{
      Environment         = var.environment
      Project             = var.project_name
      ComplianceFramework = "{framework_upper}"
      ManagedBy           = "CloudCompliance"
    }}
  }}
}}

# ==============================================================================
# CC6.1, CC6.6, CC6.7: KMS Encryption Key & Cryptographic Rotation
# ==============================================================================
resource "aws_kms_key" "compliance_key" {{
  description             = "CloudCompliance KMS master key with mandatory automatic rotation"
  deletion_window_in_days = var.kms_deletion_window_days
  enable_key_rotation     = true

  tags = {{
    Name = "${{var.project_name}}-kms-key"
  }}
}}

resource "aws_kms_alias" "compliance_key_alias" {{
  name          = "alias/${{var.project_name}}-key"
  target_key_id = aws_kms_key.compliance_key.key_id
}}

# ==============================================================================
# CC6.1, CC6.6: Secure S3 Storage with Encryption, Versioning & Public Block
# ==============================================================================
resource "aws_s3_bucket" "audit_bucket" {{
  bucket        = "${{var.project_name}}-${{var.environment}}-audit-logs"
  force_destroy = var.environment == "prod" ? false : true
}}

resource "aws_s3_bucket_versioning" "audit_bucket_versioning" {{
  bucket = aws_s3_bucket.audit_bucket.id
  versioning_configuration {{
    status = "Enabled"
  }}
}}

resource "aws_s3_bucket_server_side_encryption_configuration" "audit_bucket_crypto" {{
  bucket = aws_s3_bucket.audit_bucket.id

  rule {{
    apply_server_side_encryption_by_default {{
      kms_master_key_id = aws_kms_key.compliance_key.arn
      sse_algorithm     = "aws:kms"
    }}
  }}
}}

resource "aws_s3_bucket_public_access_block" "audit_bucket_pab" {{
  bucket = aws_s3_bucket.audit_bucket.id

  block_public_acls       = true
  block_public_policy     = true
  ignore_public_acls      = true
  restrict_public_buckets = true
}}

resource "aws_s3_bucket_policy" "enforce_tls" {{
  bucket = aws_s3_bucket.audit_bucket.id

  policy = jsonencode({{
    Version = "2012-10-17"
    Statement = [
      {{
        Sid       = "EnforceTLSRequestsOnly"
        Effect    = "Deny"
        Principal = "*"
        Action    = "s3:*"
        Resource = [
          aws_s3_bucket.audit_bucket.arn,
          "${{aws_s3_bucket.audit_bucket.arn}}/*"
        ]
        Condition = {{
          Bool = {{
            "aws:SecureTransport" = "false"
          }}
        }}
      }}
    ]
  }})
}}

# ==============================================================================
# CC6.6, CC6.7: VPC Isolation, Subnets, Security Groups & Flow Logs
# ==============================================================================
resource "aws_vpc" "main" {{
  cidr_block           = var.vpc_cidr
  enable_dns_hostnames = true
  enable_dns_support   = true

  tags = {{
    Name = "${{var.project_name}}-vpc"
  }}
}}

resource "aws_subnet" "private" {{
  vpc_id                  = aws_vpc.main.id
  cidr_block              = cidrsubnet(var.vpc_cidr, 4, 1)
  map_public_ip_on_launch = false

  tags = {{
    Name = "${{var.project_name}}-private-subnet"
  }}
}}

resource "aws_default_security_group" "default" {{
  vpc_id = aws_vpc.main.id
  # Explicitly leaving ingress/egress empty restricts unapproved traffic
}}

resource "aws_flow_log" "vpc_traffic_log" {{
  log_destination_type = "s3"
  log_destination      = aws_s3_bucket.audit_bucket.arn
  traffic_type         = "ALL"
  vpc_id               = aws_vpc.main.id
}}

# ==============================================================================
# CC7.2, CC7.3: CloudTrail Audit Logging & Metric Alarms
# ==============================================================================
resource "aws_cloudtrail" "main_audit_trail" {{
  name                          = "${{var.project_name}}-audit-trail"
  s3_bucket_name                = aws_s3_bucket.audit_bucket.id
  include_global_service_events = true
  is_multi_region_trail         = true
  enable_log_file_validation    = true
  kms_key_id                    = aws_kms_key.compliance_key.arn

  depends_on = [aws_s3_bucket_policy.enforce_tls]
}}

resource "aws_sns_topic" "compliance_alerts" {{
  name              = "${{var.project_name}}-compliance-alerts"
  kms_master_key_id = aws_kms_key.compliance_key.id
}}
'''

AWS_VARIABLES_TF = '''# Generated by CloudCompliance Wizard

variable "aws_region" {{
  description = "Target AWS deployment region"
  type        = string
  default     = "{region}"
}}

variable "environment" {{
  description = "Deployment tier (dev, staging, prod)"
  type        = string
  default     = "{environment}"
}}

variable "project_name" {{
  description = "Project or workload identifier"
  type        = string
  default     = "{project_name}"
}}

variable "vpc_cidr" {{
  description = "Base VPC IPv4 CIDR block"
  type        = string
  default     = "10.0.0.0/16"
}}

variable "kms_deletion_window_days" {{
  description = "KMS key deletion waiting period in days"
  type        = number
  default     = 30
}}
'''

AWS_TFVARS = '''# Generated by CloudCompliance Wizard
aws_region               = "{region}"
environment              = "{environment}"
project_name             = "{project_name}"
vpc_cidr                 = "10.0.0.0/16"
kms_deletion_window_days = 30
'''

ENV_EXAMPLE = '''# CloudCompliance Environment Configuration
AWS_DEFAULT_REGION={region}
AWS_REGION={region}

# Multi-Channel Alerting & Webhooks (Optional)
SLACK_WEBHOOK_URL=
TEAMS_WEBHOOK_URL=
DISCORD_WEBHOOK_URL=
GENERIC_WEBHOOK_URL=

# AI Compliance Assistant (NVIDIA NIM)
NVIDIA_API_KEY=
'''


def run_wizard(
    provider: Optional[str] = None,
    framework: Optional[str] = None,
    env: Optional[str] = None,
    services: Optional[List[str]] = None,
    region: Optional[str] = None,
    project_name: Optional[str] = None,
    output_dir: Optional[Path] = None,
    non_interactive: bool = False,
) -> Dict[str, Path]:
    """
    Execute the interactive starter wizard to bootstrap a compliant Terraform configuration.
    """
    target_dir = Path(output_dir) if output_dir else Path.cwd()
    target_dir.mkdir(parents=True, exist_ok=True)

    console.print(Panel.fit(
        "[bold cyan]⚡ CloudCompliance — Interactive Starter Wizard[/bold cyan]\n"
        "[dim]Scaffold compliance-ready infrastructure as code tailored to your stack.[/dim]",
        border_style="cyan"
    ))

    # 1. Cloud Provider
    if not provider:
        if non_interactive or not sys.stdin.isatty():
            provider = "aws"
        else:
            provider = Prompt.ask(
                "1. Which cloud provider are you targeting?",
                choices=["aws", "azure", "gcp"],
                default="aws"
            )
    provider = provider.lower()

    # 2. Compliance Framework
    if not framework:
        if non_interactive or not sys.stdin.isatty():
            framework = "soc2"
        else:
            framework = Prompt.ask(
                "2. Which primary compliance framework do you need to satisfy?",
                choices=["soc2", "hipaa", "pcidss"],
                default="soc2"
            )
    framework = framework.lower()

    # 3. Environment tier
    if not env:
        if non_interactive or not sys.stdin.isatty():
            env = "dev"
        else:
            env = Prompt.ask(
                "3. Which environment tier are you configuring?",
                choices=["dev", "staging", "prod"],
                default="dev"
            )
    env = env.lower()

    # 4. Project name & region
    if not project_name:
        if non_interactive or not sys.stdin.isatty():
            project_name = "cloudcompliance-app"
        else:
            project_name = Prompt.ask("4. Enter project / workload name", default="cloudcompliance-app")

    if not region:
        if non_interactive or not sys.stdin.isatty():
            region = "us-east-1"
        else:
            region = Prompt.ask("5. Target AWS region", default="us-east-1")

    # Generate file contents
    main_tf_content = AWS_MAIN_TF.format(
        framework_upper=framework.upper(),
        environment=env,
        provider_upper=provider.upper(),
    )
    variables_tf_content = AWS_VARIABLES_TF.format(
        region=region,
        environment=env,
        project_name=project_name,
    )
    tfvars_content = AWS_TFVARS.format(
        region=region,
        environment=env,
        project_name=project_name,
    )
    env_content = ENV_EXAMPLE.format(region=region)

    # Write files
    created_files: Dict[str, Path] = {}
    files_to_write = {
        "main.tf": main_tf_content,
        "variables.tf": variables_tf_content,
        "terraform.tfvars": tfvars_content,
        ".env.example": env_content,
    }

    for filename, content in files_to_write.items():
        file_path = target_dir / filename
        with open(file_path, "w") as f:
            f.write(content)
        created_files[filename] = file_path

    # Print summary
    console.print()
    console.print(f"[bold green]✔ Compliance project successfully initialized in {target_dir}![/bold green]\n")
    for fname, fpath in created_files.items():
        console.print(f"  • [cyan]{fname}[/cyan] → [dim]{fpath}[/dim]")

    console.print()
    console.print(Panel(
        f"[bold]Next Steps to Achieve Instant {framework.upper()} Compliance:[/bold]\n\n"
        f"  1. Review generated files:   [cyan]cd {target_dir}[/cyan]\n"
        f"  2. Initialize Terraform:     [cyan]terraform init[/cyan]\n"
        f"  3. Validate configuration:   [cyan]terraform plan[/cyan]\n"
        f"  4. Apply baseline controls:  [cyan]terraform apply[/cyan]\n"
        f"  5. Generate compliance proof:[cyan]cloudcompliance report --framework {framework} --pdf --sarif[/cyan]\n",
        title="[bold green]🚀 Ready for Deployment[/bold green]",
        border_style="green"
    ))

    return created_files
